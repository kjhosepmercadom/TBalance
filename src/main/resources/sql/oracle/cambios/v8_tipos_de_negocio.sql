-- TBalance - Oracle
-- Cambio v8 (v3.6.0): lo mismo que el de PostgreSQL (ver ese archivo).
-- La v3.6.0 se probó con PostgreSQL; este script es la traducción a Oracle.
--
-- Diferencia: Oracle guarda '' como NULL, así que TALLA y COLOR aceptan
-- NULL. En Oracle una restricción UNIQUE de varias columnas sí considera
-- repetidas dos filas "M sin color", así que UQ_VARIANTE funciona igual.
-- =====================================================================

ALTER TABLE PRODUCTO      MODIFY (STOCK NUMBER(13,3), STOCK_MIN NUMBER(13,3));
ALTER TABLE ENTRADA       MODIFY (CANTIDAD NUMBER(13,3));
ALTER TABLE SALIDA        MODIFY (CANTIDAD NUMBER(13,3));
ALTER TABLE DETALLE_VENTA MODIFY (CANTIDAD NUMBER(13,3));

ALTER TABLE PRODUCTO ADD (
  MANEJO        VARCHAR2(12 CHAR) DEFAULT 'SIMPLE' NOT NULL,
  UNIDAD_MEDIDA VARCHAR2(10 CHAR) DEFAULT 'UND'    NOT NULL,
  CONSTRAINT CK_PRODUCTO_MANEJO CHECK (MANEJO IN ('SIMPLE', 'VARIANTES')),
  CONSTRAINT CK_PRODUCTO_UNIDAD CHECK (UNIDAD_MEDIDA IN ('UND', 'M', 'KG', 'L', 'CAJA'))
);

CREATE TABLE PRODUCTO_VARIANTE (
  PERFIL_ID    VARCHAR2(20 CHAR) NOT NULL,
  ID           VARCHAR2(30 CHAR) NOT NULL,
  PRODUCTO_ID  VARCHAR2(30 CHAR) NOT NULL,
  TALLA        VARCHAR2(10 CHAR),
  COLOR        VARCHAR2(30 CHAR),
  CODIGO       VARCHAR2(60 CHAR),
  STOCK        NUMBER(13,3) DEFAULT 0 NOT NULL,
  STOCK_MIN    NUMBER(13,3) DEFAULT 0 NOT NULL,
  PRECIO_VENTA NUMBER(14,2),
  ACTIVO       NUMBER(1)    DEFAULT 1 NOT NULL,
  ORDEN        NUMBER(4)    DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PRODUCTO_VARIANTE PRIMARY KEY (PERFIL_ID, ID),
  CONSTRAINT FK_VARIANTE_PRODUCTO FOREIGN KEY (PERFIL_ID, PRODUCTO_ID)
    REFERENCES PRODUCTO (PERFIL_ID, ID) ON DELETE CASCADE,
  CONSTRAINT UQ_VARIANTE UNIQUE (PERFIL_ID, PRODUCTO_ID, TALLA, COLOR),
  CONSTRAINT CK_VARIANTE_TALLA_COLOR CHECK (TALLA IS NOT NULL OR COLOR IS NOT NULL),
  CONSTRAINT CK_VARIANTE_STOCK CHECK (STOCK >= 0 AND STOCK_MIN >= 0),
  CONSTRAINT CK_VARIANTE_ACTIVO CHECK (ACTIVO IN (0, 1))
);

ALTER TABLE DETALLE_VENTA ADD (VARIANTE_ID VARCHAR2(30 CHAR), DESCRIPCION_VARIANTE VARCHAR2(60 CHAR));
ALTER TABLE ENTRADA       ADD (VARIANTE_ID VARCHAR2(30 CHAR));
ALTER TABLE SALIDA        ADD (VARIANTE_ID VARCHAR2(30 CHAR));

ALTER TABLE DETALLE_VENTA ADD CONSTRAINT FK_DETALLE_VARIANTE FOREIGN KEY (PERFIL_ID, VARIANTE_ID)
  REFERENCES PRODUCTO_VARIANTE (PERFIL_ID, ID);
ALTER TABLE ENTRADA ADD CONSTRAINT FK_ENTRADA_VARIANTE FOREIGN KEY (PERFIL_ID, VARIANTE_ID)
  REFERENCES PRODUCTO_VARIANTE (PERFIL_ID, ID);
ALTER TABLE SALIDA ADD CONSTRAINT FK_SALIDA_VARIANTE FOREIGN KEY (PERFIL_ID, VARIANTE_ID)
  REFERENCES PRODUCTO_VARIANTE (PERFIL_ID, ID);
